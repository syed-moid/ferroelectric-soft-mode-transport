#!/usr/bin/env python3
"""T2 blinded census of mode families. Characters only: no kappa, linewidth, eta or any
scattering quantity is read or written.

Inputs per model: the renormalized 16^3 eigenvectors at 300 K (q1 = 12^3) and the bare harmonic 16^3
eigenvectors of the same model (same BORN, cell and NONANALYTIC = 3).

Phase convention. anphon's eigenvectors e carry a Bloch phase on the lattice vector only. Projections onto a
fixed in-cell pattern are then not invariant under symmetry operations that move atoms into neighbouring cells
(checked: 2646 of 4096 star members differ). All characters are therefore formed with the atom-position
convention, e~_j = e_j exp(-2 pi i q.r_j) (r_j: reduced in-cell positions); with this sign C_pol is
star-invariant to 1e-5.

Per wave vector q (reduced coordinates) and degenerate group G of renormalized modes (|dOmega| < DEG_TOL):
  C_pol(G)       = (1/|G|) sum_{nu in G} sum_{i=1..3} |<p_i|e~_nu>|^2
                   p_i: the lowest optical triplet at Gamma of the same run (branches 4-6; q = 0, so no phase)
  C_rot(G)       = (1/|G|) sum_{nu in G} sum_a w_a(q) |<rho_a(q)|e~_nu>|^2,  w_a(q) = sin^2(pi q_b) sin^2(pi q_c)
                   rho_a(q): normalized displacement pattern generated by a field of rigid octahedral rotations
                   about axis a with wave vector q (rotation theta exp(2 pi i q.R_Ti) of the octahedron centred
                   at each Ti; each O takes the mean of the displacements given by its two octahedra). For a = z:
                   O_x: -sin(pi q_x) y^, O_y: +sin(pi q_y) x^, O_z, Sr, Ti: 0 (up to a common factor).
                   On the line q_x = q_y = 1/2 (R-M) it equals the in-cell rigid-rotation pattern r_z.
                   (b, c) = the axes perpendicular to a. w_a = 1 only where neighbouring octahedra are in
                   antiphase along both b and c (rigid rotation); w_a = 0 at Gamma.
  C_rot_plain(G) = sum_a |<r_a|e~_nu>|^2 with the fixed in-cell pattern r_a, no weight (documents what a plain
                   projection does; not used for labels)
  s_unst(G)      = (1/|G|) sum_{nu in G} sum_{j: omega_j^2 < 0} |<b_j|e_nu>|^2   (b_j: bare modes at q) -> D1
  r_ren(G)       = (Omega^2 - <omega^2>) / Omega^2,  <omega^2> = (1/|G|) sum_nu sum_j |<b_j|e_nu>|^2 omega_j^2 -> D3
All are invariant under unitary rotations inside G (traces over the subspace).

Usage: t2_family_census.py OUT_PREFIX LABEL=REN_EVEC:BARE_EVEC [LABEL=REN_EVEC:BARE_EVEC ...]
Writes OUT_PREFIX_<LABEL>.csv (one row per mode on the full mesh) and prints the reference checks.
"""
import sys
from itertools import product

import numpy as np
import pandas as pd

from fekappa.evec_io import read_evec

RY_CM = 109737.31568160
DEG_TOL = 1e-3          # cm^-1
# primitive cell as built by anphon from the 2x2x2 XML (first atom of each kind in the supercell list):
# Sr (0,0,0), Ti (1/2,1/2,1/2), O (0,1/2,1/2), O (1/2,0,1/2), O (1/2,1/2,0)
POS = np.array([[0, 0, 0], [.5, .5, .5], [0, .5, .5], [.5, 0, .5], [.5, .5, 0]])
TI, OXY = 1, (2, 3, 4)
ATOM_OF = np.repeat(np.arange(5), 3)


def freq(ev2):
    return np.sign(ev2) * np.sqrt(np.abs(ev2)) * RY_CM


def rotation_patterns():
    R = np.zeros((3, 15))
    for a in range(3):
        ax = np.eye(3)[a]
        for o in OXY:
            R[a, 3 * o:3 * o + 3] = np.cross(ax, POS[o] - POS[TI])
        R[a] /= np.linalg.norm(R[a])
    return R


def rotation_field_patterns(q):
    """rho_a(q), a = x, y, z, normalized (rows); zero rows where the pattern vanishes."""
    sn = np.sin(np.pi * np.asarray(q))
    R = np.zeros((3, 15))
    for a in range(3):
        ax = np.eye(3)[a]
        for o in OXY:
            b = int(np.argmax(np.abs(POS[o] - POS[TI])))       # bond axis of this O (its offset from Ti)
            # mean of the two octahedra sharing O: amplitude sin(pi q_b), direction a x (bond vector of O
            # relative to the Ti of its own cell); the common factor i/2 is dropped
            R[a, 3 * o:3 * o + 3] = sn[b] * np.cross(ax, 2 * (POS[o] - POS[TI]))
        n = np.linalg.norm(R[a])
        if n > 1e-12:
            R[a] /= n
    return R


def groups(om):
    g, cur = [], [0]
    for n in range(1, len(om)):
        if abs(om[n] - om[cur[-1]]) < DEG_TOL:
            cur.append(n)
        else:
            g.append(cur); cur = [n]
    g.append(cur)
    return g


def star_key(q):
    f = np.abs(((np.asarray(q) + 0.5) % 1.0) - 0.5)
    return tuple(np.round(np.sort(f), 6))


def census(ren_path, bare_path):
    xk, ev2, E = read_evec(ren_path)
    xkb, ev2b, Eb = read_evec(bare_path)
    assert np.allclose(xk, xkb), "meshes differ"
    om, omb = freq(ev2), freq(ev2b)
    g0 = int(np.argmin(np.abs(xk).sum(1)))
    assert np.abs(xk[g0]).sum() < 1e-12
    P = E[g0, 3:6]                       # polar reference (rows = conjugated modes below)
    Rp = rotation_patterns()
    rows = []
    for k in range(len(xk)):
        q = xk[k]
        w = np.array([np.sin(np.pi * q[1]) ** 2 * np.sin(np.pi * q[2]) ** 2,
                      np.sin(np.pi * q[0]) ** 2 * np.sin(np.pi * q[2]) ** 2,
                      np.sin(np.pi * q[0]) ** 2 * np.sin(np.pi * q[1]) ** 2])
        e = E[k] * np.exp(-2j * np.pi * (POS @ q))[ATOM_OF][None, :]   # atom-position convention
        cp = (np.abs(P.conj() @ e.T) ** 2).sum(0)              # per mode
        cr = (w[:, None] * np.abs(rotation_field_patterns(q) @ e.T) ** 2).sum(0)
        crp = (np.abs(Rp @ e.T) ** 2).sum(0)
        ov = np.abs(Eb[k].conj() @ E[k].T) ** 2                # [bare j, ren nu]; both in the code convention
        su = ov[ev2b[k] < 0].sum(0)
        w2 = (ov * ev2b[k][:, None]).sum(0)
        key = star_key(q)
        for G in groups(om[k]):
            gid = G[0]
            vals = [x[G].mean() for x in (cp, cr, crp, su, w2)]
            for n in G:
                rows.append({"k": k, "qx": q[0], "qy": q[1], "qz": q[2], "branch": n + 1, "group": gid + 1,
                             "gdim": len(G), "Omega_cm1": om[k, n], "omega_bare_cm1": omb[k, n],
                             "C_pol": vals[0], "C_rot": vals[1], "C_rot_plain": vals[2], "s_unst": vals[3],
                             "r_ren": (ev2[k, n] - vals[4]) / ev2[k, n] if ev2[k, n] != 0 else np.nan,
                             "star": "%.4f_%.4f_%.4f" % key})
    df = pd.DataFrame(rows)
    # distances (reduced units, 2pi/a): from Gamma, and from the nearest R-M line (two components = 1/2)
    f = np.abs(((df[["qx", "qy", "qz"]].to_numpy() + 0.5) % 1.0) - 0.5)
    df["d_Gamma"] = np.linalg.norm(f, axis=1)
    d = 0.5 - f
    df["d_RM"] = np.min(np.stack([np.hypot(d[:, 1], d[:, 2]), np.hypot(d[:, 0], d[:, 2]),
                                  np.hypot(d[:, 0], d[:, 1])]), axis=0)
    # reference checks
    Rk = [k for k in range(len(xk)) if np.allclose(np.abs(xk[k]), .5)][0]
    low = np.argsort(om[Rk])[:3]
    eR = E[Rk, low] * np.exp(-2j * np.pi * (POS @ xk[Rk]))[ATOM_OF][None, :]
    R_overlap = np.linalg.svd(rotation_field_patterns(xk[Rk]) @ eR.T, compute_uv=False) ** 2   # principal overlaps of the two 3-dim spaces
    rot_on_pol = (np.abs(P.conj() @ Rp.T) ** 2).sum(0)
    info = {"Gamma_TO1_cm1": om[g0, 3:6], "R_low3_cm1": om[Rk, low], "R_triplet_vs_rigid_rotation": R_overlap,
            "rotation_pattern_on_polar_subspace": rot_on_pol, "P": P, "Rp": Rp}
    return df, info


def main():
    prefix = sys.argv[1]
    infos = {}
    for spec in sys.argv[2:]:
        lab, paths = spec.split("=", 1)
        ren, bare = paths.split(":")
        df, info = census(ren, bare)
        df.insert(0, "model", lab)
        df.to_csv(f"{prefix}_{lab}.csv", index=False, float_format="%.6g")
        infos[lab] = info
        print(lab, {k: np.round(v, 4) for k, v in info.items() if k not in ("P", "Rp")})
    labs = list(infos)
    for a, b in product(labs, labs):
        if a < b:
            Pa, Pb = infos[a]["P"], infos[b]["P"]
            print(f"polar reference overlap {a}-{b} (principal):",
                  np.round(np.linalg.svd(Pa.conj() @ Pb.T, compute_uv=False) ** 2, 5))


if __name__ == "__main__":
    main()
